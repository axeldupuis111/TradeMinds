/**
 * Rapport PDF de l'analyse IA de discipline — design brandé (kit lib/pdf/kit).
 *
 * Le rapport reprend toute l'analyse nouvelle génération : verdict, KPI,
 * coût de l'indiscipline avec courbe contrefactuelle (réel vs discipline
 * respectée), violations chiffrées, patterns avec preuves, edge, revue des
 * trades notés A-D et plan d'action.
 *
 * La page appelante fournit des chaînes DÉJÀ traduites (titres de violations,
 * segments d'edge…) : ce module ne connaît que les libellés de structure.
 */

